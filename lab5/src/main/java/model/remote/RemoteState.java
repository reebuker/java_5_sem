package model.remote;

// то, что у пульта меняется во время работы. null значит, что такого свойства у пульта нет,
// а при чтении из файла значит "в файле не задано, оставить как есть".
// Свои поля подтипов: у телевизора extra1 это прошлый канал, extra2 последний случайный;
// у стереосистемы extra1 сколько раз включали трек, extra2 последний случайный;
// у умного дома extra1 сколько раз нажали "выключить всё", extra2 сколько приборов включил
// последний сценарий
public record RemoteState(
        Integer batteryLevel, // заряд, от 0 до 100
        Boolean on, // включено ли устройство
        Integer volume, // громкость, у умного дома нет
        Integer position, // номер канала или трека, у умного дома нет
        String appliances, // приборы умного дома по символу на прибор: 1 включён, 0 выключен
        Integer extra1,
        Integer extra2) {
}
